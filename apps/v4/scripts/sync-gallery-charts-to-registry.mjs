function resolveRelative(fromFile, spec) {
  const base = path.dirname(fromFile)
  let resolved = path.resolve(base, spec)
  if (fs.existsSync(resolved) && fs.statSync(resolved).isFile()) {
    return resolved
  }
  for (const ext of [".tsx", ".ts", ".jsx", ".js"]) {
    if (fs.existsSync(resolved + ext)) return resolved + ext
  }
  // directory index
  for (const ext of [".tsx", ".ts"]) {
    const idx = path.join(resolved, `index${ext}`)
    if (fs.existsSync(idx)) return idx
  }
  return null
}

function collectModuleGraph(entryAbs) {
  const queue = [entryAbs]
  const seen = new Set()
  while (queue.length) {
    const file = queue.pop()
    if (seen.has(file)) continue
    seen.add(file)
    const content = fs.readFileSync(file, "utf8")
    for (const m of content.matchAll(RELATIVE_IMPORT_RE)) {
      const resolved = resolveRelative(file, m[1])
      if (!resolved) {
        throw new Error(
          `Unresolved relative import "${m[1]}" from ${path.relative(APP_ROOT, file)}`
        )
      }
      // Only pull modules under examples/chart
      if (!resolved.startsWith(EXAMPLES_ROOT + path.sep)) {
        throw new Error(
          `Relative import escapes examples/chart: ${m[1]} from ${path.relative(APP_ROOT, file)}`
        )
      }
      queue.push(resolved)
    }
  }
  return seen
}

function inferRegistryDependencies(contents) {
  const deps = new Set()
  const joined = contents.join("\n")

  for (const m of joined.matchAll(UI_IMPORT_RE)) {
    deps.add(m[1])
  }

  if (joined.includes("@/lib/chart-fa") || joined.includes('from "@/lib/chart-fa"')) {
    deps.add("chart-fa")
  }
  if (joined.includes("@/lib/chart-locale")) deps.add("chart-locale")
  if (joined.includes("@/lib/chart-toman-tick")) deps.add("chart-toman-tick")
  if (joined.includes("@/lib/chart-jalali-tick")) deps.add("chart-jalali-tick")
  if (joined.includes("@/lib/chart-mock-data")) deps.add("chart-mock-data")
  if (joined.includes("@/lib/chart-live")) deps.add("chart-live")
  if (joined.includes("@/lib/use-market-neon")) deps.add("use-market-neon")
  if (joined.includes("@/lib/digits")) deps.add("digits")
  if (joined.includes("@/lib/utils")) deps.add("utils")

  // Most demos use ChartContainer via ui/chart — ensure chart is present
  if (deps.has("chart") === false && joined.includes("ui/chart")) {
    deps.add("chart")
  }

  return [...deps].sort()
}

function inferNpmDependencies(contents) {
  const deps = new Set()
  const joined = contents.join("\n")
  if (
    /from\s+["']highcharts/.test(joined) ||
    /from\s+["']highcharts-react-official["']/.test(joined) ||
    /import\s+["']highcharts/.test(joined)
  ) {
    deps.add("highcharts")
    deps.add("highcharts-react-official")
  }
  if (/from\s+["']lucide-react["']/.test(joined)) {
    deps.add("lucide-react")
  }
  return [...deps].sort()
}

function formatRegistryItem(item) {
  const lines = []
  lines.push("  {")
  lines.push(`    name: ${JSON.stringify(item.name)},`)
  lines.push(`    type: "registry:block",`)
  if (item.description) {
    lines.push(`    description: ${JSON.stringify(item.description)},`)
  }
  if (item.dependencies?.length) {
    lines.push(
      `    dependencies: ${JSON.stringify(item.dependencies)},`
    )
  }
  lines.push(
    `    registryDependencies: ${JSON.stringify(item.registryDependencies, null, 0).replace(/,/g, ", ")},`
  )
  lines.push("    files: [")
  for (const file of item.files) {
    lines.push("      {")
    lines.push(`        path: ${JSON.stringify(file.path)},`)
    lines.push(`        type: ${JSON.stringify(file.type)},`)
    lines.push("      },")
  }
  lines.push("    ],")
  lines.push(
    `    categories: ${JSON.stringify(item.categories)},`
  )
  lines.push("  },")
  return lines.join("\n")
}

function syncGallery() {
  const catalog = JSON.parse(fs.readFileSync(CATALOG_PATH, "utf8"))
  const examples = catalog.examples
  if (!Array.isArray(examples) || examples.length === 0) {
    throw new Error("chart-examples.json has no examples")
  }

  rimraf(GALLERY_OUT)
  ensureDir(GALLERY_OUT)

  const items = []
  const slugs = []
  let sharedFilesWritten = 0

  for (const example of examples) {
    const { id, category, title } = example
    const entryRel = path.join(category, `${id}.tsx`)
    const entryAbs = path.join(EXAMPLES_ROOT, entryRel)
    if (!fs.existsSync(entryAbs)) {
      throw new Error(`Missing gallery demo: ${entryRel}`)
    }

    const graph = collectModuleGraph(entryAbs)
    const rewrittenContents = []
    const files = []

    for (const abs of [...graph].sort()) {
      const relFromExamples = path.relative(EXAMPLES_ROOT, abs)
      const outAbs = path.join(GALLERY_OUT, relFromExamples)
      let content = fs.readFileSync(abs, "utf8")
      content = rewriteInstallImports(content)
      writeFile(outAbs, content)
      rewrittenContents.push(content)

      const registryPath = path
        .join("charts", "gallery", relFromExamples)
        .replaceAll("\\", "/")
      const isEntry = abs === entryAbs
      files.push({
        path: registryPath,
        type: isEntry ? "registry:block" : "registry:component",
      })
      if (!isEntry) sharedFilesWritten++
    }

    // Sort entry file first
    files.sort((a, b) => {
      if (a.type === "registry:block") return -1
      if (b.type === "registry:block") return 1
      return a.path.localeCompare(b.path)
    })

    const registryDependencies = inferRegistryDependencies(rewrittenContents)
    const dependencies = inferNpmDependencies(rewrittenContents)

    items.push({
      name: id,
      description: title || undefined,
      dependencies: dependencies.length ? dependencies : undefined,
      registryDependencies,
      files,
      categories: ["charts", `charts-${category}`],
    })
    slugs.push(id)
  }

  // Patch charts/_registry.ts
  let registrySource = fs.readFileSync(CHARTS_REGISTRY_PATH, "utf8")
  const startIdx = registrySource.indexOf(GALLERY_MARKER_START)
  const endIdx = registrySource.indexOf(GALLERY_MARKER_END)

  const generatedBlock = [
    GALLERY_MARKER_START,
    ...items.map(formatRegistryItem),
    GALLERY_MARKER_END,
  ].join("\n")

  if (startIdx !== -1 && endIdx !== -1) {
    const before = registrySource.slice(0, startIdx)
    const after = registrySource.slice(endIdx + GALLERY_MARKER_END.length)
    // Remove trailing `]` from before if we're replacing inside the array —
    // markers live inside the array before the closing bracket.
    registrySource = before + generatedBlock + after
  } else {
    // Insert before the final `]\n` of the charts array.
    const lastBracket = registrySource.lastIndexOf("\n]")
    if (lastBracket === -1) {
      throw new Error("Could not find end of charts array in _registry.ts")
    }
    registrySource =
      registrySource.slice(0, lastBracket) +
      "\n" +
      generatedBlock +
      registrySource.slice(lastBracket)
  }

  writeFile(CHARTS_REGISTRY_PATH, registrySource)

  // Gallery slug set for middleware
  const slugSource = `/** Auto-generated by scripts/sync-gallery-charts-to-registry.mjs — do not edit. */
export const GALLERY_CHART_SLUGS = new Set<string>([
${slugs.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
])
`
  writeFile(SLUGS_PATH, slugSource)

  return {
    demoCount: items.length,
    sharedFilesWritten,
    slugCount: slugs.length,
  }
}

function main() {
  console.log("📦 Syncing chart libs → registry/new-york-v4/lib …")
  copyLibSources()
  writeLibRegistry()

  console.log("📊 Syncing gallery demos → registry/new-york-v4/charts/gallery …")
  const result = syncGallery()

  console.log(
    `✅ Synced ${result.demoCount} demos (+ shared modules), ${result.slugCount} slugs`
  )
}

main()
