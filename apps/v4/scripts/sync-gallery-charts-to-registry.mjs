/**
 * Sync catalogued gallery demos (examples/chart) into installable registry
 * items under registry/new-york-v4/charts/gallery/ with the same ids.
 *
 * Also syncs shared chart libs into registry/new-york-v4/lib/ and regenerates
 * lib/gallery-chart-slugs.ts for middleware rewrites.
 *
 * Usage: node apps/v4/scripts/sync-gallery-charts-to-registry.mjs
 * (cwd: apps/v4 or repo root)
 */

import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const APP_ROOT = path.resolve(__dirname, "..")
const EXAMPLES_ROOT = path.join(APP_ROOT, "examples", "chart")
const REGISTRY_ROOT = path.join(APP_ROOT, "registry", "new-york-v4")
const GALLERY_OUT = path.join(REGISTRY_ROOT, "charts", "gallery")
const LIB_OUT = path.join(REGISTRY_ROOT, "lib")
const CATALOG_PATH = path.join(APP_ROOT, "lib", "chart-examples.json")
const CHARTS_REGISTRY_PATH = path.join(
  REGISTRY_ROOT,
  "charts",
  "_registry.ts"
)
const LIB_REGISTRY_PATH = path.join(LIB_OUT, "_registry.ts")
const SLUGS_PATH = path.join(APP_ROOT, "lib", "gallery-chart-slugs.ts")

const GALLERY_MARKER_START =
  "// @generated by sync-gallery-charts-to-registry.mjs — do not edit"
const GALLERY_MARKER_END = "// @generated end"

const LIB_SOURCES = [
  "digits.ts",
  "chart-locale.ts",
  "chart-mock-data.ts",
  "chart-fa.ts",
  "chart-toman-tick.tsx",
  "chart-jalali-tick.tsx",
]

const UI_IMPORT_RE =
  /@\/registry\/new-york-v4\/ui\/([a-z0-9-]+)/g
const RELATIVE_IMPORT_RE =
  /from\s+["'](\.[^"']+)["']/g
const ABSOLUTE_IMPORT_RE =
  /from\s+["'](@\/[^"']+)["']/g

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true })
}

function rimraf(dir) {
  fs.rmSync(dir, { recursive: true, force: true })
}

function writeFile(filePath, content) {
  ensureDir(path.dirname(filePath))
  fs.writeFileSync(filePath, content, "utf8")
}

function rewriteInstallImports(content) {
  return content
    .replaceAll(
      "@/components/chart-live",
      "@/lib/chart-live"
    )
    .replaceAll(
      "@/examples/chart/area/use-market-neon",
      "@/lib/use-market-neon"
    )
}

function copyLibSources() {
  for (const name of LIB_SOURCES) {
    const src = path.join(APP_ROOT, "lib", name)
    const dest = path.join(LIB_OUT, name)
    if (!fs.existsSync(src)) {
      throw new Error(`Missing lib source: ${src}`)
    }
    writeFile(dest, fs.readFileSync(src, "utf8"))
  }

  // chart-live stub + use-market-neon are authored in registry (not copied)
  if (!fs.existsSync(path.join(LIB_OUT, "chart-live.tsx"))) {
    throw new Error("Missing registry/new-york-v4/lib/chart-live.tsx stub")
  }
  if (!fs.existsSync(path.join(LIB_OUT, "use-market-neon.ts"))) {
    throw new Error("Missing registry/new-york-v4/lib/use-market-neon.ts")
  }
}

